#ifndef RGL_IMGQA_FIELD_DIFF_METRIC_H
#define RGL_IMGQA_FIELD_DIFF_METRIC_H
//
// field_diff_metric.h — **两枚标量场配成对之后，「差」的连续量统计口径**（mean + p99）。
//
// ## 为什么开这一层（不这么做会发生什么）
//
// 债-154 的实测证据：影场四格里「远点·门关」的二值翻转率是四格**最低**的（0.029 %），而它的
// 连续量 mean(Δcov) = 22.564 ‰，比门开那格差 31.8 倍 ⟹ **只看翻转率的判据会把这一类缺陷读成
// 「更好」**。`shadow-swim-flat` 因此把 mean + p99 提为主判据；`material-swim` 要补同一条，
// 而它俩的「差」住在两个完全不同的域里：
//
//   · 影场 = **像素域搬运**（B 的网格上双线性采样 cov 场，分母 = 零位移的固定可信集）
//   · 材质场 = **世界格对拍**（5 cm 格逐格中位数，分母 = 两机的共同格）
//
// 配对口径**不能合并**（精度域也不同：影场必须 double，float32 在 |x| = 1e6 处 ULP = 0.0625 m；
// 材质场刻意保持 float32，换精度会挪动格归属 = 改 `swim` 的判据）。但**统计量本身必须只有
// 一份**——尤其「p99 取哪个下标」这一条：两台仪器都报 p99，若一个用 `floor(0.99·(n−1))` 一个用
// 「第 99 个百分位的线性插值」，那两个 p99 数字**看着可比、其实不可比**，而没有任何一条判据会红。
// 这正是 AGENTS 哲学第 1 条点名的形态（单一来源不承重，「访问路径必须消费那个来源」才承重）。
//
// ## 🔴 泛化的边界在哪（写死，免得后来人往这里堆）
//
// 本层只吃**已经配好对的一串 |Δ|**，除此之外什么都不知道：
//   · 不知道 Δ 是粗糙度还是阴影覆盖度（单位由调用侧决定，本层不换算、不猜量纲）；
//   · 不知道配对怎么来的（像素搬运 / 世界格查表 / 将来的体素），也不管分母固定在哪个位移上；
//   · 不做二值翻转（那是各仪器自己的阈值语义：`cov > kSeamBin` vs `median < thr`）；
//   · 不设阈值——「多大算坏」是判据，住各仪器的 judge TU，住这里就成了两台仪器共用一个界
//     （影场的 2.0 ‰ 与材质场的界**本来就该不同**，共用即错）。
// ⟹ 一句话：**「怎么配对」不归本层，「配对之后怎么数」不归调用侧。**
//
// ## 变异红线（哪个变异让本层红；逐条实跑读数见 `selftest_field_diff.cpp` 头注）
//   · p99 下标从 `floor(0.99·(n−1))` 改成 `ceil(0.99·n)`（或任何别的分位口径）→ 闭式用例红；
//   · p99 写成「取最大值」→ 尾部与均值分不开的那条用例红（p99 与 max 在偏置样本集上必须不同）；
//   · p99 写成「取中位数」→ 同上那条红（反向：两者也不许相等）；
//   · mean 的分母从 n 改成「样本总数含空集」→ 空集用例红（空集必须回 0，不许 NaN）；
//   · mean 忘了 ×1000 → 千分点口径那条红（判据界写的是 ‰，漂成比例口径 = 界被静默放宽 1000 倍）。
//
#include <cstddef>
#include <vector>

namespace RGL::imgqa {

/// 一组 |Δ| 样本的均值，**千分点**（‰）口径：`1000 · sumAbs / n`。
/// `n == 0` → **0.0**（不是 NaN）：本层的契约是「没有样本就没有差」，而「分母是彩票」这件事
/// 由各仪器的规模闸门负责抛（`shadow-swim-flat` 的 G4 / `material-swim` 的 G4/G5）——统计层
/// 出 NaN 会让「闸门本该红」退化成「打印出 nan 但判据比不出大小 ⟹ 恒假 ⟹ 绿」。
[[nodiscard]] double meanAbsPermille(double sumAbs, std::size_t n);

/// 一组 |Δ| 样本的 p99，**与输入同单位**（不是千分点；调用侧要 ‰ 就自己 ×1000，
/// 因为本层不知道单位）。空集 → 0.0，理由同 `meanAbsPermille`。
/// 🔴 下标口径 = `floor(0.99 · (n − 1))`，用 `nth_element`（O(n)）取那一个分位——
/// 全项目**只有这一处**定义 p99。副作用：把入参打乱（调用侧此后不许再依赖它的顺序）；
/// 材质场那边是「先算完 p99 再打印样本数」，顺序本来就不进判据。
[[nodiscard]] double p99Abs(std::vector<double>& absDiffs);

}  // namespace RGL::imgqa
#endif  // RGL_IMGQA_FIELD_DIFF_METRIC_H
