/// 注册入口（对外接口不变，见 `judgments_table.h`）：拼接顺序 = 被测对象两条在前、量具自证两条
/// 在后（J5 → J6 → J7 → J8），与 `material_swim.cpp` 里 `pushVerdicts` 的产出顺序一致。
const std::vector<JudgmentInfo>& materialSwimContinuousJudgments()
{
    static const std::vector<JudgmentInfo> kAll = [] {
        std::vector<JudgmentInfo> out;
        const auto& field = continuousFieldLines();
        const auto& instrument = continuousInstrumentLines();
        out.insert(out.end(), field.begin(), field.end());
        out.insert(out.end(), instrument.begin(), instrument.end());
        return out;
    }();
    return kAll;
}

