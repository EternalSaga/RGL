// compute-access 两份产物的字符串字面量转义（不含外层引号）。
// 手写而不是 nlohmann::dump：本产物是**已提交文件**且进 SHA1 护栏，格式必须我们自己钉死
// （2 空格缩进 + 每行一条 param + 键序 binding/param/access）才有人读得动 diff；
// dump(2) 的键序是字典序、每个键各占一行，改不动。
static std::string jsonString(std::string_view s)
{
	std::string out;
	out.reserve(s.size() + 2);
	for (const char c : s) {
		switch (c) {
		case '"': out += "\\\""; break;
		case '\\': out += "\\\\"; break;
		case '\n': out += "\\n"; break;
		case '\t': out += "\\t"; break;
		case '\r': out += "\\r"; break;
		default: out.push_back(c);
		}
	}
	return out;
}

// compute-bindings 产物里的一个条目：binding 变量名 + `[[vk::binding(N)]]` 的号。
// 与 JSON 产物同一次遍历产出（见 compute-access 子命令），只是**过滤后**的子集：
// 只含 descriptor-table-slot 型参数。
struct ComputeBindingEntry {
	std::string name;
	uint32_t binding = 0;
};

// shader 文件名 → C++ 标识符片段（`izb_create.comp.slang` → `izb_create_comp`）。
// 非 [A-Za-z0-9_] 一律换成 '_'：产物里的数组名要能编过，而文件名由 shader 目录决定。
static std::string bindingIdentifier(std::string_view shaderFile)
{
	std::string id;
	id.reserve(shaderFile.size());
	for (const char c : shaderFile)
		id.push_back((c == '_' || (c >= '0' && c <= '9') || (c >= 'a' && c <= 'z')
		              || (c >= 'A' && c <= 'Z'))
			? c
			: '_');
	return id;
}

// compute-bindings 产物（rgl/generated/compute_bindings_generated.cppm）全文。
//
// 手写模板而不是 inja：与 JSON 产物同一个理由——已提交文件 + SHA1 护栏，格式必须自己钉死
// 才有人读得动 diff。两个产物**同源同次生成**（同一次编译遍历、同一份 byShader）⟹ 结构上
// 不可能互不一致，这是"扩展现有子命令而不是新加一条管线"买到的东西。
//
// 排序 = 调用方给的 map 序（shader 名字典序）+ 表内 binding 升序，两边都已在 compute-access
// 里排好；本函数只负责照抄成文本，不再排第二次（排两次 = 两份可能漂的口径）。
static std::string generateComputeBindingsCppm(
	const std::string& moduleName,
	const std::map<std::string, std::vector<ComputeBindingEntry>>& byShader)
{
	std::string t = "// Auto-generated by reflection_tool (compute-access) — DO NOT EDIT\n"
		"//\n"
		"// compute shader 的 **binding 变量名 → binding 号** 接口表。真相源 = 各 .comp.slang 里的\n"
		"// `[[vk::binding(N)]]` 声明（构建期 Slang 反射）；与同一次遍历产出的 compute_access.json 同源\n"
		"// ⟹ 两份产物不可能互不一致。新鲜度 = rgl/generated/reflection_manifest.txt 的 SHA1 守卫。\n"
		"//\n"
		"// 消费者 = rgl/shader.cppm 的 makeMappedCompute：调用点按**名字**声明「哪个堆槽喂给哪个\n"
		"// binding」，号在此查表。存在的理由 = 杀掉「手抄 binding 号」这条静默错——shader 改号而 C++\n"
		"// 不动时没有任何东西会响（无编译错、无反射校验、无 VVL 报错），只是往错的堆槽读数据。\n"
		"//\n"
		"// 收录范围 = 全部 descriptor-table-slot 型全局参数；`[[vk::push_constant]]` 不入表\n"
		"// （descriptor heap 下 push data 由 vkCmdPushDataEXT 自动供给，没有映射条目可映射）。\n"
		"export module " + moduleName + ";\n"
		"\n"
		"import rlstd;\n"
		"\n"
		"namespace RGL {\n"
		"\n"
		"\t// 一枚 binding：shader 里的 binding 变量名 + 它的 `[[vk::binding(N)]]` 号。\n"
		"\texport struct RgComputeBinding {\n"
		"\t\tstd::string_view name;\n"
		"\t\tuint32_t binding;\n"
		"\t};\n";
	for (const auto& [shader, rows] : byShader) {
		if (rows.empty())
			continue;  // 无 binding 的 shader 只在下面总表里留一条空 span，不开一个空数组
		t += "\n\t// " + shader + "（" + std::to_string(rows.size()) + " 个 descriptor-table-slot 参数）\n";
		t += "\tinline constexpr std::array<RgComputeBinding, " + std::to_string(rows.size())
			+ "> kComputeBindings_" + bindingIdentifier(shader) + "{{\n";
		for (const auto& r : rows)
			t += "\t\t{\"" + jsonString(r.name) + "\", " + std::to_string(r.binding) + "},\n";
		t += "\t}};\n";
	}
	t += "\n\t// 一张表 = shader 文件名（basename，与 SPV 同名只差后缀）+ 它的 binding 表。\n"
		"\tstruct RgComputeShaderBindings {\n"
		"\t\tstd::string_view shader;\n"
		"\t\tstd::span<const RgComputeBinding> bindings;\n"
		"\t};\n"
		"\n\t// 全部 compute 的接口表，按 shader 名升序（确定性排序：产物是已提交文件，\n"
		"\t// 假 diff 教人跳过 diff，护栏就废了）。\n"
		"\tinline constexpr std::array<RgComputeShaderBindings, " + std::to_string(byShader.size())
		+ "> kComputeBindingTables{{\n";
	for (const auto& [shader, rows] : byShader) {
		t += "\t\t{\"" + jsonString(shader) + "\", ";
		// 空表直接给空 span（上面没为它开数组），非空才引用那个 constexpr 数组
		t += rows.empty()
			? "std::span<const RgComputeBinding>{}"
			: "std::span<const RgComputeBinding>(kComputeBindings_" + bindingIdentifier(shader) + ")";
		t += "},\n";
	}
	t += "\t}};\n"
		"\n\t// shader 名清单由表派生（不给名字单开一份可能漂的副本）。\n"
		"\tinline constexpr auto kComputeShaderNames = [] {\n"
		"\t\tstd::array<std::string_view, kComputeBindingTables.size()> names{};\n"
		"\t\tfor (unsigned i = 0; i < names.size(); ++i)\n"
		"\t\t\tnames[i] = kComputeBindingTables[i].shader;\n"
		"\t\treturn names;\n"
		"\t}();\n"
		"\n\t// 一枚 shader 的全部 binding 条目；shader 不在表里 = 空 span（调用方负责报错并列出\n"
		"\t// computeShaderNames()）。线性扫：表长 = compute 枚数（个位数），且只在 shader object\n"
		"\t// 创建期查一次（🔴 不是每帧路径——见 shader.cppm 的构造期红线）。\n"
		"\texport inline std::span<const RgComputeBinding> computeBindings(std::string_view shader) {\n"
		"\t\tfor (const auto& entry : kComputeBindingTables)\n"
		"\t\t\tif (entry.shader == shader)\n"
		"\t\t\t\treturn entry.bindings;\n"
		"\t\treturn {};\n"
		"\t}\n"
		"\n\t// 表里有哪些 shader（报错时列清单用）。\n"
		"\texport inline std::span<const std::string_view> computeShaderNames() {\n"
		"\t\treturn kComputeShaderNames;\n"
		"\t}\n"
		"\n}  // namespace RGL\n";
	return t;
}

