static void printUsage() {
	auto* logger = RGL::RLLogger::getInstance();
	logger->info("Usage:");
	logger->info("  reflection_tool validate  --json <path> --schema <path>");
	logger->info("  reflection_tool generate  --json <path> --schema <path> --output <path> --module-name <name> --template <path>");
	logger->info("  reflection_tool render     --json <path> --output <path> --template <path>");
	logger->info("  reflection_tool slang      --shader <path> [--shader <path>...] --schema <path> --output <path> --module-name <name> --template <path> [--flags <a b c ...>]");
	logger->info("  reflection_tool compute-access --shader <path> [--shader <path>...] --output <path> [--output-cppm <path> --module-name <name>] [--flags <a b c ...>] [--include <path>]");
	logger->info("  reflection_tool compute-push --shader <path> [--shader <path>...] --output <path> --module-name <name> --template <path> [--flags <a b c ...>] [--include <path>]");
}

int main(int argc, char* argv[]) {
	RGL::RLLogger::initialize(LOG_CONFIG_PATH);
	auto* logger = RGL::RLLogger::getInstance();
	logger->debug("reflection_tool started, pid={}", ::getpid());

	try {
		std::string command;
		std::string jsonPath, schemaPath, outputPath, moduleName, templatePath, slangFlagsStr;
		std::string outputCppmPath;  // compute-access 的第二份产物（binding 名 → 号 的接口表）
		std::vector<std::string> shaderPaths, includePaths;

		po::options_description desc("Options");
		desc.add_options()("help,h", "produce help message")("json,j", po::value<std::string>(&jsonPath), "path to slangc reflection JSON")("schema,s", po::value<std::string>(&schemaPath), "path to Lua schema file")("output,o", po::value<std::string>(&outputPath), "output .cppm file path")("module-name,m", po::value<std::string>(&moduleName), "C++ module name for generated .cppm")("template,t", po::value<std::string>(&templatePath), "path to inja template file")("shader", po::value<std::vector<std::string>>(&shaderPaths), "slang source file(s) for 'slang' command (repeatable)")("flags", po::value<std::string>(&slangFlagsStr), "space-separated slang compiler flags for 'slang' (SLANG_FLAGS; boost 不吞 dash 参数故用单串 split)")("include,I", po::value<std::vector<std::string>>(&includePaths), "slang search path(s) for 'slang' (repeatable; -I)")("output-cppm", po::value<std::string>(&outputCppmPath), "second output of 'compute-access': the binding-name -> binding-number interface table (.cppm); requires --module-name");

		if (argc < 2) {
			printUsage();
			return 1;
		}

		command = argv[1];
		int cmdArgc = argc - 1;
		char* cmdArgv[1024];
		std::ranges::copy_n(argv + 1, cmdArgc, cmdArgv);

		po::variables_map vm;
		po::store(po::command_line_parser(cmdArgc, cmdArgv).options(desc).run(), vm);
		po::notify(vm);

		if (vm.count("help")) {
			printUsage();
			return 0;
		}

		// slang 子命令不消费 JSON（直接链接 libslang.so 查 API）
		if (command == "slang") {
#ifdef RGL_TOOLS_WITH_SLANG
			if (shaderPaths.empty()) {
				logger->error("--shader is required for 'slang'");
				return 1;
			}
			if (vm["schema"].empty() || outputPath.empty() || moduleName.empty() || templatePath.empty()) {
				logger->error("'slang' requires --schema --output --module-name --template");
				return 1;
			}
			// flags：--flags 单串 split（缺省 = kDefaultSlangFlags）；-I 搜索路径追加
			std::vector<std::string> flags;
			if (slangFlagsStr.empty()) {
				flags = kDefaultSlangFlags;
			} else {
				std::string remaining = slangFlagsStr;
				size_t pos;
				while ((pos = remaining.find(' ')) != std::string::npos) {
					flags.push_back(remaining.substr(0, pos));
					remaining.erase(0, pos + 1);
				}
				if (!remaining.empty())
					flags.push_back(remaining);
			}
			for (const auto& inc : includePaths) {
				flags.push_back("-I");
				flags.push_back(inc);
			}
			RGL::Schema schema = RGL::loadSchema(schemaPath);
			RGL::SlangContext ctx;
			std::string diag;
			if (!ctx.compile(shaderPaths, flags, diag)) {
				logger->error("[FAIL] slang compile: {}", diag);
				return 1;
			}
			logger->info("[OK] slang compile succeeded, querying API");
			// 按 schema 顺序查询 + 交叉校验（vertexLayouts 先，pushConstants 后）
			std::vector<RGL::SlangStruct> structs;
			bool ok = true;
			// 批 R：嵌套契约 struct 名的合法判据 = 本 schema 的 vertexLayouts 名单
			// （vertexAttrCppType / validateSlangVertexLayout 与 generateCppmFromSlang 同源）
			std::set<std::string> contractStructs;
			for (const auto& vl : schema.vertexLayouts)
				if (!vl.name.empty())
					contractStructs.insert(vl.name);
			for (const auto& vl : schema.vertexLayouts) {
				if (vl.name.empty()) continue;
				auto api = ctx.queryStruct(vl.name);
				if (!api) {
					logger->error("[FAIL] vertexLayout '{}': struct not found in shader", vl.name);
					ok = false;
					continue;
				}
				if (!RGL::validateSlangVertexLayout(*api, vl, contractStructs)) ok = false;
				else {
					logger->info("[PASS] vertexLayout '{}' matches API (size={} fields={})",
						vl.name, api->size, api->fields.size());
					structs.push_back(std::move(*api));
				}
			}
			for (const auto& pc : schema.pushConstants) {
				if (pc.name.empty()) continue;
				auto api = ctx.queryPushConst(pc.name);
				if (!api) {
					logger->error("[FAIL] pushConst '{}': not found / not a constant buffer", pc.name);
					ok = false;
					continue;
				}
				if (!RGL::validateSlangPushConst(*api, pc)) ok = false;
				else {
					logger->info("[PASS] pushConst '{}' -> struct '{}' matches API (size={})",
						pc.name, api->name, api->size);
					structs.push_back(std::move(*api));
				}
			}
			if (!ok) {
				logger->error("[FAIL] slang cross-validation failed");
				return 1;
			}
			std::optional<std::string> cppm = RGL::generateCppmFromSlang(structs, schema, templatePath, moduleName);
			if (!cppm) {
				logger->error("[FAIL] Generation aborted");
				return 1;
			}
			std::ofstream out(outputPath);
			if (!out.is_open()) {
				logger->error("Cannot open output file: {}", outputPath);
				return 1;
			}
			out << *cppm;
			logger->info("[OK] Generated {} (slang API path)", outputPath);
			return 0;
#else
			// 债-25：configure 未找到 Slang C API 库时的可归因出口（编译面已剔除 slang_reflect）
			logger->error("'slang' 子命令不可用：本构建未链接 Slang C API（SLANG_PREBUILT_DIR "
				"缺失或不完整）。Linux 先 just config 触发 FetchContent 再 just reflect（债-25）");
			return 1;
#endif
		}

		// compute-access 子命令：compute entry 的 binding 表，**一次编译遍历出两份产物**。
		//   ① --output       = 已提交 JSON（rgl/generated/compute_access.json）：binding + 参数名 +
		//                       读写方向，消费者 = B2-2 的图外依赖图（方向表）。
		//   ② --output-cppm  = 已提交 .cppm（rgl/generated/compute_bindings_generated.cppm）：
		//                       binding **变量名 → 号** 的接口表，消费者 = rgl/shader.cppm 的
		//                       makeMappedCompute（调用点从此不再手抄 binding 号）。
		// 🔴 两份产物**同源同次生成**是这条子命令的形状决定的，不要拆成两条管线：拆了就是给
		// 将来留一对可能互不一致的口径（同一张 binding 表查两次，各自可能漏一枚 shader）。
		// 曾配过一条 checks 基线规则，经复核不合格已撤（单源 + 评论文件 ≠ 双相对账，
		// 判据 → docs/compute_调研.md §7.12）。别因为"没有消费者"就删它：产物是九枚 compute 的
		// binding 表第一次成为已提交的机器可读事实，新鲜度由 reflection_manifest 的 SHA1 守卫守。
		// 立论 → docs/compute_调研.md §7.10/§7.11：图外 compute 的同步对账要回答「这个 dispatch
		// 会写哪些资源」，而人工申报的申报者与被判者是同一个人 ⟹ 需要一条独立机器来源。
		if (command == "compute-access") {
#ifdef RGL_TOOLS_WITH_SLANG
			if (shaderPaths.empty()) {
				logger->error("--shader is required for 'compute-access'");
				return 1;
			}
			if (outputPath.empty()) {
				logger->error("--output is required for 'compute-access'");
				return 1;
			}
			// flags：--flags 单串 split（缺省 = kDefaultSlangFlags）；-I 搜索路径追加
			std::vector<std::string> flags;
			if (slangFlagsStr.empty()) {
				flags = kDefaultSlangFlags;
			} else {
				std::string remaining = slangFlagsStr;
				size_t pos;
				while ((pos = remaining.find(' ')) != std::string::npos) {
					flags.push_back(remaining.substr(0, pos));
					remaining.erase(0, pos + 1);
				}
				if (!remaining.empty())
					flags.push_back(remaining);
			}
			for (const auto& inc : includePaths) {
				flags.push_back("-I");
				flags.push_back(inc);
			}
			// 入口名回写进产物：它由 --flags 决定（CMake 传 -entry main）。写死 "main" 的话，
			// 改了 flags 产物会**谎报入口**——方向表谎报入口比少一条更难查。
			std::string entry = "main";
			for (size_t i = 0; i + 1 < flags.size(); ++i)
				if (flags[i] == "-entry")
					entry = flags[i + 1];
			struct ParamRow {
				uint32_t binding = 0;
				std::string param;
				std::string access;
				// 是否 descriptor-table-slot 型（= compute-bindings 产物的收录判据；
				// push constant 为假——它没有映射条目可映射）
				bool tableSlot = false;
			};
			// 一个 shader 一个 SlangContext：那个类禁止 compile 两次（第二次直接 error），
			// 而方向表要覆盖全部 compute 入口。std::map 的键序 = shader 名字典序（产物排序
			// 的一半在这里免费拿到，另一半是 params 显式 sort）。
			std::map<std::string, std::vector<ParamRow>> byShader;
			for (const auto& shader : shaderPaths) {
				RGL::SlangContext ctx;
				std::string diag;
				// 🔴 错误必须归因到具体文件：多 shader 一次调用只转述 diag 的话，人会去改
				// 最后动过的那一枚——诊断指错文件 = 让人靠猜决定改哪个 shader。
				if (!ctx.compile(std::vector<std::string>{ shader }, flags, diag)) {
					logger->error("[FAIL] compute-access 编译 {} 失败：{}", shader, diag);
					return 1;
				}
				const std::string base = fs::path(shader).filename().string();
				// basename 是产物的键（绝对路径进产物 = 产物不可移植，换机器/换 worktree 全
				// 量假 diff）。同名输入会让键互相覆盖 = 产物静默少一枚 shader。
				if (byShader.contains(base)) {
					logger->error("[FAIL] compute-access：{} 与既有输入 basename 同名（{}）"
						"——产物的 shader 键会互相覆盖，去掉重复输入", shader, base);
					return 1;
				}
				auto& rows = byShader[base];
				for (const auto& g : ctx.queryGlobalParams())
					rows.push_back(ParamRow{ g.binding, g.name, g.access, g.descriptorTableSlot });
				// 🔴 确定性排序：产物是**已提交文件**且进 SHA1 护栏，不排序 = 每次 just
				// reflect 都可能产生与语义无关的假 diff（假 diff 教人跳过 diff，护栏就废了）。
				std::ranges::sort(rows, [](const ParamRow& a, const ParamRow& b) {
					return a.binding != b.binding ? a.binding < b.binding : a.param < b.param;
				});
				logger->info("[OK] compute-access {}: {} 个 global 参数", base, rows.size());
			}
			// 全部 shader 编译成功才落笔：半途失败留下半份产物 = 下一轮 checks 拿它当真相。
			std::string text = "{\n"
				"  \"note\": \"compute entry point 的 binding 读写方向；真相源 = Slang 反射，勿手改\",\n"
				"  \"shaders\": [\n";
			for (auto it = byShader.begin(); it != byShader.end(); ++it) {
				text += "    {\n      \"shader\": \"" + jsonString(it->first)
					+ "\",\n      \"entry\": \"" + jsonString(entry)
					+ "\",\n      \"params\": [";
				for (size_t i = 0; i < it->second.size(); ++i)
					text += (i ? ",\n" : "\n") + std::string("        {\"binding\": ")
						+ std::to_string(it->second[i].binding) + ", \"param\": \""
						+ jsonString(it->second[i].param) + "\", \"access\": \""
						+ jsonString(it->second[i].access) + "\"}";
				text += it->second.empty() ? "]\n    }" : "\n      ]\n    }";
				text += std::next(it) == byShader.end() ? "\n" : ",\n";
			}
			text += "  ]\n}\n";
			std::ofstream out(outputPath);
			if (!out.is_open()) {
				logger->error("Cannot open output file: {}", outputPath);
				return 1;
			}
			out << text;
			logger->info("[OK] Generated {} ({} 枚 compute shader)", outputPath, byShader.size());
			// 第二份产物 = binding 名 → 号 的接口表（.cppm）。🔴 **同一次遍历、同一份 byShader**
			// 里产出：两份产物结构上不可能互不一致（"名字键"与"方向表"讲的是同一张 binding 表，
			// 分成两条管线各查一次 = 给将来留一对可能漂的口径）。
			//
			// 收录判据 = tableSlot（push constant 不收，理由见 ParamRow）；表内顺序沿用上面已排好的
			// binding 升序，shader 顺序沿用 map 的键序（= 文件名字典序）。
			if (!outputCppmPath.empty()) {
				if (moduleName.empty()) {
					logger->error("'compute-access' 给了 --output-cppm 就必须给 --module-name");
					return 1;
				}
				std::map<std::string, std::vector<ComputeBindingEntry>> slots;
				for (const auto& [shader, rows] : byShader) {
					// 🔴 先建键再填条目：一枚 shader 即使**一个 table-slot 参数都没有**也要留在表里
					// （表 = 管线名单的镜像）。否则"表少一枚"有两种成因（管线漏登记 / 恰好无 binding），
					// 覆盖锚点就分不清，而消费端还会对一枚合法 shader 抛"不在表里"。
					auto& dst = slots[shader];
					for (const auto& r : rows)
						if (r.tableSlot)
							dst.push_back(ComputeBindingEntry{ r.param, r.binding });
				}
				// 数组名由文件名消毒而来：两个不同文件名撞成同一个标识符 = 产物重复定义
				// （编译期才炸、且错误指向生成物）。现在拦，别留给下游。
				std::map<std::string, std::string> seenId;
				for (const auto& [shader, rows] : slots) {
					const std::string id = bindingIdentifier(shader);
					if (auto it = seenId.find(id); it != seenId.end()) {
						logger->error("[FAIL] compute-access：文件名 {} 与 {} 消毒成同一个标识符 {}"
							"——产物会出现重复定义，改名或去掉一枚",
							shader, it->second, id);
						return 1;
					}
					seenId[id] = shader;
				}
				std::ofstream outCppm(outputCppmPath);
				if (!outCppm.is_open()) {
					logger->error("Cannot open output file: {}", outputCppmPath);
					return 1;
				}
				outCppm << generateComputeBindingsCppm(moduleName, slots);
				logger->info("[OK] Generated {} ({} 枚 shader 的 binding 名表)", outputCppmPath,
					slots.size());
			}
			return 0;
#else
			// 与 'slang' 子命令同一个可归因出口：静默产出空产物 = 规则侧拿一份**看起来正常**
			// 的方向表去对账，比直接失败危险得多（假绿的入口往往是"看起来成功"的工具）。
			logger->error("'compute-access' 子命令不可用：本构建未链接 Slang C API（"
				"SLANG_PREBUILT_DIR 缺失或不完整）。Linux 先 just config 触发 FetchContent "
				"再 just reflect（债-25）");
			return 1;
#endif
		}

		// compute-push 子命令：从 compute shader 反射 push constant 的 C++ struct（产 .cppm）。
		//
		// 🔴 **本管线没有 schema，也不该有**（docs/compute_调研.md §7.12 定案：双相对账成立的
		// 前提 = 两个来源各自携带对方推不出的信息）。图形侧 6 份 *_schema.lua 配得上存在，是因为
		// 它带 heapSlotOffset（运行期堆槽 = reservedSlots() + offset，C++ 侧分配策略，shader 里
		// 根本没有）；而 compute push 的 schema 只能写 stride/offset/字段名——**全部是从 shader
		// 手抄的派生信息**，按那条判据它不是真第二来源。本管线的提取清单是**隐式**的：「给定这些
		// shader，每个的 push constant」，所以参数里只有 shader 名单。
		//
		// 修的现实：八枚 compute 的 push 契约在 C++ 侧手写镜像 struct，而它们那几条
		// `static_assert(offsetof(...))` **量的是手抄的 C++ struct、不是 shader** ⟹ shader 把两个
		// uint 换序而 C++ 没动时三条 assert 全过（关于 C++ 侧的同义反复）。本产物让布局第一次
		// 有出处：字段名/偏移/尺寸 = 编译器实查真值，改 shader 字段名 = 产品代码编译失败。
		if (command == "compute-push") {
#ifdef RGL_TOOLS_WITH_SLANG
			if (shaderPaths.empty()) {
				logger->error("--shader is required for 'compute-push'");
				return 1;
			}
			if (outputPath.empty() || moduleName.empty() || templatePath.empty()) {
				logger->error("'compute-push' requires --output --module-name --template");
				return 1;
			}
			// flags：--flags 单串 split（缺省 = kDefaultSlangFlags）；-I 搜索路径追加
			std::vector<std::string> flags;
			if (slangFlagsStr.empty()) {
				flags = kDefaultSlangFlags;
			} else {
				std::string remaining = slangFlagsStr;
				size_t pos;
				while ((pos = remaining.find(' ')) != std::string::npos) {
					flags.push_back(remaining.substr(0, pos));
					remaining.erase(0, pos + 1);
				}
				if (!remaining.empty())
					flags.push_back(remaining);
			}
			for (const auto& inc : includePaths) {
				flags.push_back("-I");
				flags.push_back(inc);
			}
			// 一枚 shader 一个 SlangContext（与 compute-access 同形）：八枚 compute 全都声明
			// 全局 `push` 与 `main`，塞进同一次编译请求必炸（conflicting declaration /
			// function 'main' already has a body / ambiguous reference to 'push'）。
			//
			// std::map 的键序 = 类型名字典序 ⟹ 确定性排序的一半免费拿到（另一半是字段按 offset
			// 显式 sort）。产物是**已提交文件**且进 SHA1 护栏，不排序 = 每次 just reflect 都可能
			// 产生与语义无关的假 diff。
			std::map<std::string, RGL::SlangStruct> byType;
			for (const auto& shader : shaderPaths) {
				RGL::SlangContext ctx;
				std::string diag;
				// 🔴 错误必须归因到具体文件（compute-access 同款）：多 shader 一次调用只转述
				// diag 的话，人会去改最后动过的那一枚。
				if (!ctx.compile(std::vector<std::string>{ shader }, flags, diag)) {
					logger->error("[FAIL] compute-push 编译 {} 失败：{}", shader, diag);
					return 1;
				}
				const std::string base = fs::path(shader).filename().string();
				// 🔴 selectivity 自检（先于一切提取）：判别子必须**恰好**命中 1 个全局参数。
				//   · 命中 0 = 这枚 shader 没有 push constant，或判别子失效；
				//   · 命中 >1 = 判别子过宽，会把 sceneHeader 这类真 ConstantBuffer 一起捞进产物
				//     = 生成一份 shader 里根本不存在的布局。
				// 两种都不是"少一个 struct"的小事，而是产物整体不再等于「shader 的 push 契约」
				// ⟹ 直接失败并点名实测命中数，绝不静默产出一份看起来正常的产物（假绿的入口
				// 往往是"看起来成功"的工具）。
				const std::vector<std::string> names = ctx.queryPushConstParamNames();
				if (names.size() != 1) {
					std::string seen;
					for (const auto& n : names) {
						if (!seen.empty())
							seen += ", ";
						seen += n;
					}
					logger->error("[FAIL] compute-push {}：判别子命中 {} 个 push constant 参数"
						"（应为恰好 1 个；命中名：{}）",
						base, names.size(), names.empty() ? std::string("<无>") : seen);
					return 1;
				}
				auto api = ctx.queryPushConst(names[0]);
				if (!api) {
					logger->error("[FAIL] compute-push {}：push 参数 '{}' 的元素不是 struct"
						"（queryPushConst 拒收）", base, names[0]);
					return 1;
				}
				// 字段按 offset 升序：反射的字段序本就等于声明序，显式排一次是为了让"产物按
				// offset 单调可读"成为不依赖 slang 版本迭代序的性质。
				std::ranges::sort(api->fields, [](const RGL::SlangField& a, const RGL::SlangField& b) {
					return a.offset < b.offset;
				});
				logger->info("[OK] compute-push {}: push '{}' -> struct '{}' (size={} {} 字段)",
					base, names[0], api->name, api->size, api->fields.size());
				// 同名 struct 撞车 = 产物里两份同名定义（编译期才炸，且错误指向生成物）。
				// 现在不拦，将来加第二枚同 push 类型的 shader 时会拿到一份编不过的产物。
				if (!byType.emplace(api->name, *api).second) {
					logger->error("[FAIL] compute-push {}：struct 名 '{}' 已被前面的输入产出"
						"——产物会出现重复定义，去掉重复输入", base, api->name);
					return 1;
				}
			}
			// 全部 shader 成功才落笔：半途失败留下半份产物 = 下一轮拿它当真相。
			// 生成走**现成模板 + 现成 generator 路径**（types_cppm.inja + generateCppmFromSlang），
			// 空 Schema = 无 slots/constants：本产物只有 struct，没有堆槽与契约常量。
			std::vector<RGL::SlangStruct> structs;
			structs.reserve(byType.size());
			for (auto& [name, s] : byType)
				structs.push_back(std::move(s));
			std::optional<std::string> cppm =
				RGL::generateCppmFromSlang(structs, RGL::Schema{}, templatePath, moduleName);
			if (!cppm) {
				logger->error("[FAIL] compute-push 生成中止（见 [FAIL] 条目）");
				return 1;
			}
			std::ofstream out(outputPath);
			if (!out.is_open()) {
				logger->error("Cannot open output file: {}", outputPath);
				return 1;
			}
			out << *cppm;
			logger->info("[OK] Generated {} ({} 个 push struct)", outputPath, byType.size());
			return 0;
#else
			// 与 slang / compute-access 同一个可归因出口：静默产出空产物 = 消费者按一份
			// "看起来正常"的布局发字段（假绿）。
			logger->error("'compute-push' 子命令不可用：本构建未链接 Slang C API（"
				"SLANG_PREBUILT_DIR 缺失或不完整）。Linux 先 just config 触发 FetchContent "
				"再 just reflect（债-25）");
			return 1;
#endif
		}

		// validate / generate / render 走 JSON 路径
		if (jsonPath.empty() || !fs::exists(jsonPath)) {
			logger->error("Reflection JSON not found: {}", jsonPath);
			return 1;
		}

		std::ifstream jsonFile(jsonPath);
		json reflection = json::parse(jsonFile);
		logger->debug("Loaded reflection JSON: {} parameters", reflection["parameters"].size());

		if (command == "validate") {
			if (vm["schema"].empty()) {
				logger->error("--schema is required for 'validate'");
				return 1;
			}
			auto schema = RGL::loadSchema(schemaPath);
			bool ok = RGL::validateSchema(reflection, schema);
			if (ok) {
				logger->info("[PASS] Schema validation passed");
				return 0;
			} else {
				logger->error("[FAIL] Schema validation failed");
				return 1;
			}

		} else if (command == "generate") {
			if (outputPath.empty()) {
				logger->error("--output is required for 'generate'");
				return 1;
			}
			if (moduleName.empty()) {
				logger->error("--module-name is required for 'generate'");
				return 1;
			}
			if (templatePath.empty()) {
				logger->error("--template is required for 'generate'");
				return 1;
			}

			// schema 必传：缺省 = 跳过校验直接生成（不安全模式，旧实现静默放行；
			// CMake 恒传 --schema，仅 CLI 误用会踩）
			if (vm["schema"].empty()) {
				logger->error("--schema is required for 'generate' (skips validation otherwise)");
				return 1;
			}
			RGL::Schema schema = RGL::loadSchema(schemaPath);
			if (!RGL::validateSchema(reflection, schema)) {
				logger->error("[FAIL] Schema validation failed before generation");
				return 1;
			}
			logger->info("[PASS] Schema validation passed, generating .cppm");

			std::optional<std::string> cppm = RGL::generateCppm(reflection, schema, templatePath, moduleName);
			if (!cppm) {
				logger->error("[FAIL] Generation aborted by layout validation — see [FAIL] entries");
				return 1;
			}
			std::ofstream out(outputPath);
			if (!out.is_open()) {
				logger->error("Cannot open output file: {}", outputPath);
				return 1;
			}
			out << *cppm;
			logger->info("[OK] Generated {}", outputPath);
			return 0;

		} else if (command == "render") {
			if (outputPath.empty()) {
				logger->error("--output is required for 'render'");
				return 1;
			}
			if (templatePath.empty()) {
				logger->error("--template is required for 'render'");
				return 1;
			}

			std::string cppm = RGL::renderTemplate(reflection, templatePath);
			std::ofstream out(outputPath);
			if (!out.is_open()) {
				logger->error("Cannot open output file: {}", outputPath);
				return 1;
			}
			out << cppm;
			logger->info("[OK] Rendered {}", outputPath);
			return 0;

		} else {
			logger->error("Unknown command: {}", command);
			printUsage();
			return 1;
		}

	} catch (const po::error& e) {
		logger->error("Error: {}", e.what());
		printUsage();
		return 1;
	} catch (const std::exception& e) {
		logger->error("Error: {}", e.what());
		return 1;
	}
}
